export function bandsForRole(role: string) {
  return bands.filter((b) => b.role === role);
}

/** Histogram of total comp implied by the published bands, in ₹ lakh buckets. */
export function distributionFor(role: string) {
  const rows = bandsForRole(role);
  const buckets = [
    { bucket: "0–10", min: 0, max: 10 },
    { bucket: "10–20", min: 10, max: 20 },
    { bucket: "20–30", min: 20, max: 30 },
    { bucket: "30–40", min: 30, max: 40 },
    { bucket: "40–60", min: 40, max: 60 },
    { bucket: "60–80", min: 60, max: 80 },
    { bucket: "80+", min: 80, max: Infinity },
  ];
  return buckets.map((b) => {
    const count = rows.reduce((acc, r) => {
      const points = [r.p25, r.p50, r.p90];
      const hits = points.filter((p) => p >= b.min && p < b.max).length;
      return acc + Math.round((hits / 3) * r.sample);
    }, 0);
    return { bucket: b.bucket, count };
  });
}
